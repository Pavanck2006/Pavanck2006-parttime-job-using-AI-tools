  t(key) {
    return this.strings[this.currentLang]?.[key] || this.strings.en[key] || key;
  },

  setLanguage(lang) {
    this.currentLang = lang;
    localStorage.setItem('lang', lang);
    this.applyTranslations();
  },

  applyTranslations() {
    // Translatable elements use data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translated = this.t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        if (el.hasAttribute('placeholder')) el.placeholder = translated;
        else el.value = translated;
      } else {
        el.textContent = translated;
      }
    });

    // Translatable placeholder elements use data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = this.t(el.getAttribute('data-i18n-placeholder'));
    });

    // Update all language selector buttons
    const label = this.currentLang === 'kn' ? 'ಕನ್ನಡ' : 'English';
    document.querySelectorAll('#langSelectBtn, #langSelectBtnAuth').forEach(btn => {
      btn.textContent = label;
    });
  }
